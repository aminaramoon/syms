// Phase 2 of docs/NOTES_DESIGN.md: matches a parsed NoteBlock to exactly one
// symbol node (shared by `symhow notes sync`, which persists the result into the
// `symhow_note*` cache, and NotesStore.h's read-path overlay, which needs the
// exact same matching decision without writing anything), and `syncNotes()`,
// the `symhow notes sync` engine itself.
namespace symhow::notes
{

enum class MatchKind
{
    Matched,
    Unmatched,   // resolveSymbol() found zero candidates for block.heading
    Ambiguous,   // >1 candidate and signature narrowing didn't get to exactly 1
};

struct MatchOutcome
{
    MatchKind kind = MatchKind::Unmatched;

    // Only meaningful when kind == Matched.
    int64_t nodeId = 0;
    std::string serializedName;
    std::string qualifiedName;  // DecodedName::namePath()
    std::string signature;      // DecodedName::signature()

    // Phase 3: set when kind == Matched, resolveSymbol() found exactly one
    // candidate for block.heading (no signature-based narrowing was needed
    // or possible), and block.signature.text is non-empty but its
    // normalizeSignature()'d form matches neither the candidate's full
    // signature nor its parameter-list suffix. The block still matches (one
    // candidate is one candidate), but the written signature disagrees with
    // reality -- e.g. a note's `### signature` fence wasn't updated after
    // the symbol's parameter list changed. `detail` (below) carries the
    // "expected ... found ..." message in this case.
    bool signatureMismatch = false;

    // Human-readable detail: candidate ids + signatures for Ambiguous;
    // "expected '...', found '...'" for a Matched signatureMismatch; empty
    // otherwise (Unmatched's message is generated by the caller since it
    // doesn't need per-block detail).
    std::string detail;
};

// Resolves `block.heading` (a qualified name, exactly as symhow::query::
// resolveSymbol() expects) against every kind, then narrows an Ambiguous
// result by normalizeSignature() equality against `block.signature.text` --
// first the full stored signature, then (if that matches nothing) just the
// parameter-list suffix starting at the first '(' character, so a stored
// `f(int)` still matches a decoded `void f(int)`. See docs/NOTES_DESIGN.md's
// "Matching" section (added by this phase's brief) for the exact rule.
MatchOutcome matchBlock(symhow::db::Database& db, const NoteBlock& block);

struct SyncCounts
{
    std::size_t files = 0;
    std::size_t blocks = 0;
    std::size_t matched = 0;
    std::size_t unmatched = 0;
    std::size_t ambiguous = 0;
    std::size_t duplicateTarget = 0;
    std::size_t filled = 0;
    std::size_t stale = 0;
    std::size_t unanchored = 0;  // note_hash empty (no staleness anchor)
    std::size_t lintProblems = 0;
    std::size_t signatureMismatch = 0;  // Phase 3: matched blocks whose written signature disagrees with the symbol's
    std::size_t orphanedFiles = 0;      // Phase 3: notes files whose source path no longer exists in the DB
};

struct SyncProblem
{
    std::string path;  // relative to notesDir
    int line = 0;
    std::string heading;
    std::string kind;  // parser Problem::kind values, or "unmatched"/"ambiguous"/"duplicate-target"
    std::string message;
};

struct SyncResult
{
    SyncCounts counts;
    std::vector<SyncProblem> problems;
};

// Parses every `*.md` under `notesDir`, matches every block against `dbPath`
// (opened once, read-write, via symhow::db::WritableDb), and rebuilds
// `symhow_note`/`symhow_note_file`/`symhow_note_problem` from scratch inside a single
// transaction (notes are few; a full rebuild is simpler and more
// deterministic than incremental diffing). Also sets `meta.symhow_notes_dir`
// (absolute path) and `meta.symhow_notes_synced_at`. `strict` is passed through
// to symhow::notes::parseNotesFile(); a "missing-section" problem from strict
// mode counts toward `lintProblems` like every other parser problem.
//
// Exit-code contract for callers: 0 always from this function itself (it
// doesn't exit/throw on note problems, only on I/O or DB errors, which
// surface as std::runtime_error); the CLI maps `strict && !result.problems
// .empty()` to exit code 3.
SyncResult syncNotes(const std::string& dbPath, const std::string& notesDir, bool strict);

}  // namespace symhow::notes
