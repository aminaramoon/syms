#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum MatchKind {
    #[default]
    Matched,
    Unmatched, // resolve_symbol() found zero candidates for block.heading
    Ambiguous, // >1 candidate and signature narrowing didn't get to exactly 1
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct MatchOutcome {
    pub kind: MatchKind,

    // Only meaningful when kind == Matched.
    pub node_id: i64,
    pub serialized_name: String,
    pub qualified_name: String, // DecodedName::name_path()
    pub signature: String,     // DecodedName::signature()

    // Phase 3: set when kind == Matched, resolve_symbol() found exactly one
    // candidate for block.heading (no signature-based narrowing was needed
    // or possible), and block.signature.text is non-empty but its
    // normalize_signature()'d form matches neither the candidate's full
    // signature nor its parameter-list suffix. The block still matches (one
    // candidate is one candidate), but the written signature disagrees with
    // reality -- e.g. a note's `### signature` fence wasn't updated after
    // the symbol's parameter list changed. `detail` (below) carries the
    // "expected ... found ..." message in this case.
    pub signature_mismatch: bool,

    // Human-readable detail: candidate ids + signatures for Ambiguous;
    // "expected '...', found '...'" for a Matched signatureMismatch; empty
    // otherwise (Unmatched's message is generated by the caller since it
    // doesn't need per-block detail).
    pub detail: String,
}

/// Compares two signature strings for the "parameter-list suffix" fallback:
/// the text from the first '(' onward (inclusive), or the whole (already
/// normalize_signature()-normalized) string if it has no '('.
fn param_suffix(normalized_sig: &str) -> &str {
    match normalized_sig.find('(') {
        Some(p) => &normalized_sig[p..],
        None => normalized_sig,
    }
}

fn json_array(items: &[String]) -> String {
    let mut j = serde_json::Value::Array(Vec::new());
    if let serde_json::Value::Array(arr) = &mut j {
        for s in items {
            arr.push(serde_json::Value::String(s.clone()));
        }
    }
    j.to_string()
}

/// Resolves `block.heading` (a qualified name, exactly as
/// `symhow::query::resolve_symbol` expects) against every kind, then narrows
/// an Ambiguous result by normalize_signature() equality against
/// `block.signature.text` -- first the full stored signature, then (if that
/// matches nothing) just the parameter-list suffix starting at the first '('
/// character, so a stored `f(int)` still matches a decoded `void f(int)`.
/// See docs/NOTES_DESIGN.md's "Matching" section for the exact rule.
pub fn match_block(db: &Database, block: &NoteBlock) -> Result<MatchOutcome> {
    let rr = resolve_symbol(db, &block.heading, None, None)?;

    if rr.candidates.is_empty() {
        return Ok(MatchOutcome {
            kind: MatchKind::Unmatched,
            ..Default::default()
        });
    }

    // Exactly one candidate already, before any signature-based narrowing --
    // matches unconditionally (one candidate is one candidate), but flag a
    // "signature-mismatch" when the block's own `### signature` disagrees
    // with it (see MatchOutcome::signature_mismatch's doc comment).
    if rr.candidates.len() == 1 {
        let c = &rr.candidates[0];
        let decoded = decode_serialized_name(&c.serialized_name);
        let mut out = MatchOutcome {
            kind: MatchKind::Matched,
            node_id: c.id,
            serialized_name: c.serialized_name.clone(),
            qualified_name: decoded.name_path(),
            signature: decoded.signature(),
            ..Default::default()
        };

        if !block.signature.text.is_empty() {
            let want_full = super::markdown::normalize_signature(&block.signature.text);
            let want_suffix = param_suffix(&want_full).to_string();
            let have_full = super::markdown::normalize_signature(&decoded.signature());
            let have_suffix = param_suffix(&have_full).to_string();
            if have_full != want_full && have_suffix != want_suffix {
                out.signature_mismatch = true;
                out.detail = format!("expected '{}', found '{}'", want_full, have_full);
            }
        }
        return Ok(out);
    }

    let mut pool = rr.candidates.clone();
    {
        let want_full = super::markdown::normalize_signature(&block.signature.text);
        let want_suffix = param_suffix(&want_full).to_string();

        let mut filtered = Vec::new();
        for c in &pool {
            let decoded = decode_serialized_name(&c.serialized_name);
            let have_full = super::markdown::normalize_signature(&decoded.signature());
            let have_suffix = param_suffix(&have_full).to_string();
            if !want_full.is_empty() && (have_full == want_full || have_suffix == want_suffix) {
                filtered.push(c.clone());
            }
        }
        pool = filtered;
    }

    if pool.len() == 1 {
        let decoded = decode_serialized_name(&pool[0].serialized_name);
        return Ok(MatchOutcome {
            kind: MatchKind::Matched,
            node_id: pool[0].id,
            serialized_name: pool[0].serialized_name.clone(),
            qualified_name: decoded.name_path(),
            signature: decoded.signature(),
            ..Default::default()
        });
    }

    // Either the original resolve_symbol() call was itself Ambiguous and
    // signature narrowing didn't get to exactly 1 (0 or >1 left), or (rare)
    // it was already >1 with no narrowing possible.
    let mut detail = String::from("candidates: ");
    for (i, c) in rr.candidates.iter().enumerate() {
        if i > 0 {
            detail.push_str("; ");
        }
        let decoded = decode_serialized_name(&c.serialized_name);
        detail.push_str(&format!("#{} {}", c.id, decoded.signature()));
    }
    Ok(MatchOutcome {
        kind: MatchKind::Ambiguous,
        detail,
        ..Default::default()
    })
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SyncCounts {
    pub files: usize,
    pub blocks: usize,
    pub matched: usize,
    pub unmatched: usize,
    pub ambiguous: usize,
    pub duplicate_target: usize,
    pub filled: usize,
    pub stale: usize,
    pub unanchored: usize, // note_hash empty (no staleness anchor)
    pub lint_problems: usize,
    pub signature_mismatch: usize, // Phase 3: matched blocks whose written signature disagrees with the symbol's
    pub orphaned_files: usize,     // Phase 3: notes files whose source path no longer exists in the DB
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SyncProblem {
    pub path: String, // relative to notes_dir
    pub line: i32,
    pub heading: String,
    pub kind: String, // parser Problem::kind values, or "unmatched"/"ambiguous"/"duplicate-target"/...
    pub message: String,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SyncResult {
    pub counts: SyncCounts,
    pub problems: Vec<SyncProblem>,
}

/// std::filesystem::absolute(): prepend the current working directory, no
/// '.'/'..' normalization.
fn absolute_path(path: &str) -> Result<PathBuf> {
    let p = Path::new(path);
    if p.is_absolute() {
        Ok(p.to_path_buf())
    } else {
        let cwd =
            std::env::current_dir().map_err(|e| Error::new(format!("cannot determine current directory: {}", e)))?;
        Ok(cwd.join(p))
    }
}

/// Recursively collects every regular `*.md` file under `dir` (full paths),
/// mirroring the C++ recursive_directory_iterator walks.
pub(super) fn collect_md_files(dir: &Path, out: &mut Vec<String>) -> Result<()> {
    let entries =
        std::fs::read_dir(dir).map_err(|e| Error::new(format!("cannot read directory '{}': {}", dir.display(), e)))?;
    for entry in entries {
        let entry =
            entry.map_err(|e| Error::new(format!("cannot read directory '{}': {}", dir.display(), e)))?;
        let path = entry.path();
        let is_symlink = entry
            .file_type()
            .map_err(|e| Error::new(format!("cannot stat '{}': {}", path.display(), e)))?
            .is_symlink();
        // std::filesystem's e.is_regular_file()/is_directory() follow
        // symlinks, but recursive_directory_iterator does not descend into
        // directory symlinks.
        let md = std::fs::metadata(&path)
            .map_err(|e| Error::new(format!("cannot stat '{}': {}", path.display(), e)))?;
        if md.is_dir() && !is_symlink {
            collect_md_files(&path, out)?;
        } else if md.is_file() && path.extension().map(|e| e == "md").unwrap_or(false) {
            out.push(path.to_string_lossy().into_owned());
        }
    }
    Ok(())
}

/// `std::filesystem::relative(full, root).generic_string()` for paths that
/// were constructed as root/<subpath> (the only shape the walk produces).
pub(super) fn relative_generic(full: &Path, root: &Path) -> String {
    full.strip_prefix(root)
        .map(|rel| {
            rel.components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/")
        })
        .unwrap_or_default()
}

/// Reads a file as a String (like the C++ ifstream into std::string; a file
/// that can't be opened reads as empty, and invalid UTF-8 is replaced
/// lossily).
pub(super) fn read_file_lossy(full: &Path) -> String {
    std::fs::read(full)
        .map(|bytes| String::from_utf8_lossy(&bytes).into_owned())
        .unwrap_or_default()
}

/// "%Y-%m-%dT%H:%M:%SZ" UTC timestamp, like the C++ strftime(buf, ..., gmtime(&t)).
fn utc_timestamp_now() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    let days = secs.div_euclid(86400);
    let rem = secs.rem_euclid(86400);
    // Howard Hinnant's civil_from_days.
    let z = days + 719468;
    let era = if z >= 0 { z } else { z - 146096 } / 146097;
    let doe = (z - era * 146097) as u64;
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    let y = yoe as i64 + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as i64;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as i64;
    let y = if m <= 2 { y + 1 } else { y };
    format!(
        "{:04}-{:02}-{:02}T{:02}:{:02}:{:02}Z",
        y,
        m,
        d,
        rem / 3600,
        (rem % 3600) / 60,
        rem % 60
    )
}

/// Parses every `*.md` under `notes_dir`, matches every block against the DB
/// at `db_path` (opened once, read-write, via `WritableDb`), and rebuilds
/// `symhow_note`/`symhow_note_file`/`symhow_note_problem` from scratch inside
/// a single transaction (notes are few; a full rebuild is simpler and more
/// deterministic than incremental diffing). Also sets
/// `meta.symhow_notes_dir` (absolute path) and `meta.symhow_notes_synced_at`.
/// `strict` is passed through to `parse_notes_file()`; a "missing-section"
/// problem from strict mode counts toward `lint_problems` like every other
/// parser problem.
///
/// Exit-code contract for callers: 0 always from this function itself (it
/// doesn't fail on note problems, only on I/O or DB errors, which surface as
/// `Error`); the CLI maps `strict && !result.problems.is_empty()` to exit
/// code 3 (see `sync_exit_code()`).
pub fn sync_notes(db_path: &str, notes_dir: &str, strict: bool) -> Result<SyncResult> {
    let mut result = SyncResult::default();

    let notes_root = absolute_path(notes_dir)?;

    let mut md_files: Vec<String> = Vec::new();
    if notes_root.is_dir() {
        collect_md_files(&notes_root, &mut md_files)?;
    }
    md_files.sort();
    result.counts.files = md_files.len();

    // Parse every file first (no DB handle needed for this part).
    let mut parsed: Vec<NotesFile> = Vec::with_capacity(md_files.len());
    for full in &md_files {
        let content = read_file_lossy(Path::new(full));
        let rel_path = relative_generic(Path::new(full), &notes_root);
        parsed.push(parse_notes_file(&content, &rel_path, strict));
    }

    let mut wdb = WritableDb::open(db_path, false)?;
    wdb.exec(K_CREATE_NOTE_TABLE_SQL)?;
    wdb.exec(K_CREATE_NOTE_FILE_TABLE_SQL)?;
    wdb.exec(K_CREATE_NOTE_PROBLEM_TABLE_SQL)?;

    wdb.begin()?;
    let work: Result<()> = (|| {
        wdb.exec("DELETE FROM symhow_note;")?;
        wdb.exec("DELETE FROM symhow_note_file;")?;
        wdb.exec("DELETE FROM symhow_note_problem;")?;

        // Need a read-only Database handle to run resolve_symbol()/
        // body_hash_for_node() against the same file -- WritableDb's own
        // in-progress transaction is visible to a second connection to the
        // same file only once committed, but all matching happens against
        // `node`/`symbol`/`occurrence`/`source_location`/`filecontent`/
        // `file`, tables this sync never modifies, so reading them through a
        // fresh read-only Database opened on the same path is safe and
        // simple (same reasoning as Sync.cpp).
        let rdb = Database::open(db_path, 0)?;

        let mut matched_node_to_heading_path: HashMap<i64, String> = HashMap::new(); // nodeId -> "path:line" of first match

        // Phase 3 "orphaned-file" detection: a notes file whose source path
        // (its own path with the trailing ".md" stripped) no longer exists
        // as a `file` row -- e.g. after `git mv`ing the source file without
        // moving its notes alongside it. Only meaningful when
        // symhow_repo_root is known (nothing to resolve the relative path
        // against otherwise); silently skipped when it isn't.
        let repo_root_for_orphan_check =
            get_meta(rdb.conn(), "symhow_repo_root").unwrap_or_default();

        let synced_at = utc_timestamp_now();

        for file in &parsed {
            if !repo_root_for_orphan_check.is_empty()
                && file.path.len() > 3
                && file.path.ends_with(".md")
            {
                let source_path = &file.path[..file.path.len() - 3];
                let abs_source = if source_path.starts_with('/') {
                    // operator/ with an absolute rhs replaces the base.
                    lexical_normalize(source_path)
                } else {
                    lexical_normalize(&format!("{}/{}", repo_root_for_orphan_check, source_path))
                };
                let mut exists = false;
                rdb.run("SELECT 1 FROM file WHERE path = ?", [abs_source.as_str()], |_row| {
                    exists = true;
                    Ok(())
                })?;
                if !exists {
                    result.counts.orphaned_files += 1;
                    result.problems.push(SyncProblem {
                        path: file.path.clone(),
                        line: 1,
                        heading: String::new(),
                        kind: "orphaned-file".to_string(),
                        message: format!("source file '{}' no longer exists in the index", source_path),
                    });
                }
            }

            for p in &file.problems {
                result.problems.push(SyncProblem {
                    path: file.path.clone(),
                    line: p.line,
                    heading: String::new(),
                    kind: p.kind.clone(),
                    message: p.message.clone(),
                });
                result.counts.lint_problems += 1;
            }

            for b in &file.blocks {
                result.counts.blocks += 1;

                let mo = match_block(&rdb, b)?;
                if mo.kind == MatchKind::Unmatched {
                    result.counts.unmatched += 1;
                    result.problems.push(SyncProblem {
                        path: file.path.clone(),
                        line: b.heading_line,
                        heading: b.heading.clone(),
                        kind: "unmatched".to_string(),
                        message: format!("no symbol matches heading '{}'", b.heading),
                    });
                    continue;
                }
                if mo.kind == MatchKind::Ambiguous {
                    result.counts.ambiguous += 1;
                    result.problems.push(SyncProblem {
                        path: file.path.clone(),
                        line: b.heading_line,
                        heading: b.heading.clone(),
                        kind: "ambiguous".to_string(),
                        message: format!("heading '{}' is ambiguous -- {}", b.heading, mo.detail),
                    });
                    continue;
                }

                if let Some(already) = matched_node_to_heading_path.get(&mo.node_id) {
                    result.counts.duplicate_target += 1;
                    result.problems.push(SyncProblem {
                        path: file.path.clone(),
                        line: b.heading_line,
                        heading: b.heading.clone(),
                        kind: "duplicate-target".to_string(),
                        message: format!("resolves to the same symbol as {} -- ignored", already),
                    });
                    continue;
                }
                matched_node_to_heading_path
                    .insert(mo.node_id, format!("{}:{}", file.path, b.heading_line));

                if mo.signature_mismatch {
                    result.counts.signature_mismatch += 1;
                    result.problems.push(SyncProblem {
                        path: file.path.clone(),
                        line: b.heading_line,
                        heading: b.heading.clone(),
                        kind: "signature-mismatch".to_string(),
                        message: format!("heading '{}' -- {}", b.heading, mo.detail),
                    });
                }

                let current_body_hash = body_hash::body_hash_for_node(&rdb, mo.node_id)?;
                let stale = !b.body_hash.is_empty() && !current_body_hash.is_empty() && b.body_hash != current_body_hash;
                let filled = b.filled();

                result.counts.matched += 1;
                if filled {
                    result.counts.filled += 1;
                }
                if stale {
                    result.counts.stale += 1;
                }
                if b.body_hash.is_empty() {
                    result.counts.unanchored += 1;
                }

                let pre_j = json_array(&b.pre.items);
                let post_j = json_array(&b.post.items);
                let bugs_j = json_array(&b.bugs.items);
                let sug_j = json_array(&b.suggestions.items);
                wdb.exec_bound(
                    "INSERT INTO symhow_note(serialized_name, qualified_name, notes_path, heading_line, brief, what, how, \
                     signature_text, pre_json, post_json, bugs_json, suggestions_json, filled, note_hash, note_commit, \
                     current_body_hash, stale, synced_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    rusqlite::params![
                        mo.serialized_name,
                        mo.qualified_name,
                        file.path,
                        b.heading_line,
                        b.brief,
                        b.what.text,
                        b.how.text,
                        mo.signature,
                        pre_j,
                        post_j,
                        bugs_j,
                        sug_j,
                        if filled { 1 } else { 0 },
                        b.body_hash,
                        b.commit,
                        current_body_hash,
                        if stale { 1 } else { 0 },
                        synced_at,
                    ],
                )?;
            }
        }

        for full in &md_files {
            let rel_path = relative_generic(Path::new(full), &notes_root);
            let content = read_file_lossy(Path::new(full));
            let content_hash = hex16(fnv1a64(&content));
            let mtime_ns: i64 = std::fs::metadata(full)
                .and_then(|m| m.modified())
                .ok()
                .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
                .map(|d| d.as_nanos() as i64)
                .unwrap_or(0);

            wdb.exec_bound(
                "INSERT INTO symhow_note_file(notes_path, mtime_ns, content_hash) VALUES (?,?,?)",
                rusqlite::params![rel_path, mtime_ns, content_hash],
            )?;
        }

        for p in &result.problems {
            wdb.exec_bound(
                "INSERT INTO symhow_note_problem(notes_path, line, heading, kind, message) VALUES (?,?,?,?,?)",
                rusqlite::params![p.path, p.line, p.heading, p.kind, p.message],
            )?;
        }

        set_meta(&wdb, "symhow_notes_dir", &notes_root.to_string_lossy())?;
        set_meta(&wdb, "symhow_notes_synced_at", &synced_at)?;

        Ok(())
    })();

    match work {
        Ok(()) => wdb.commit()?,
        Err(e) => {
            wdb.rollback()?;
            return Err(e);
        }
    }

    Ok(result)
}

/// The `symhow notes sync --json` output envelope (runNotesSync's JSON
/// construction in Cli.cpp), key-for-key: `symhow_version`, `schema`
/// ("symhow.notes-sync/1"), `database`, `notes_dir`, `counts{...}`, and a
/// `problems` array of `{path, line, heading, kind, message}` objects.
pub fn sync_json(result: &SyncResult, symhow_version: &str, db_path: &str, notes_dir: &str) -> serde_json::Value {
    let abs_notes_dir = match absolute_path(notes_dir) {
        Ok(p) => p.to_string_lossy().into_owned(),
        Err(_) => notes_dir.to_string(),
    };

    let counts = serde_json::json!({
        "files": result.counts.files,
        "blocks": result.counts.blocks,
        "matched": result.counts.matched,
        "unmatched": result.counts.unmatched,
        "ambiguous": result.counts.ambiguous,
        "duplicate_target": result.counts.duplicate_target,
        "filled": result.counts.filled,
        "stale": result.counts.stale,
        "unanchored": result.counts.unanchored,
        "lint_problems": result.counts.lint_problems,
        "signature_mismatch": result.counts.signature_mismatch,
        "orphaned_files": result.counts.orphaned_files,
    });

    let problems: Vec<serde_json::Value> = result
        .problems
        .iter()
        .map(|p| {
            serde_json::json!({
                "path": p.path,
                "line": p.line,
                "heading": p.heading,
                "kind": p.kind,
                "message": p.message,
            })
        })
        .collect();

    serde_json::json!({
        "symhow_version": symhow_version,
        "schema": "symhow.notes-sync/1",
        "database": db_path,
        "notes_dir": abs_notes_dir,
        "counts": counts,
        "problems": problems,
    })
}

/// The CLI's exit-code contract for `symhow notes sync`: 0 normally, 3 when
/// `--strict` was given and any problem (lint or sync) was reported.
pub fn sync_exit_code(strict: bool, result: &SyncResult) -> i32 {
    if strict && !result.problems.is_empty() {
        3
    } else {
        0
    }
}
