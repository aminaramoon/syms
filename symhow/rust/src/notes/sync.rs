//! Phase 2 of docs/NOTES_DESIGN.md: matches a parsed NoteBlock to exactly one
//! symbol node (shared by `symhow notes sync`, which persists the result into
//! the `symhow_note*` cache, and the read-path overlay in `notes_store.rs`,
//! which needs the exact same matching decision without writing anything),
//! and `sync_notes()`, the `symhow notes sync` engine itself. Mirrors
//! `symhow::notes::Sync.{h,cpp}`; the `--json` output envelope and exit-code
//! contract of the CLI verb (`runNotesSync` in Cli.cpp) live here as
//! `sync_json()`/`sync_exit_code()` so the exact key names survive the port.

